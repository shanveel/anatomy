"""Build the poster gallery: optimised images, the gallery markup in index.html, and the download ZIP.

The original JPEGs in assets/posters/<slug>.jpg are never changed; visitors download them as they are.
For each poster this makes:
  <slug>-thumb-320.avif, <slug>-thumb-560.avif, <slug>-thumb-560.webp   gallery thumbnails
  <slug>-720.avif, <slug>-full.avif, <slug>-full.webp                   full-screen viewer
plus a tiny blurred preview embedded in the page, so every tile shows something the moment the page appears.

To add or remove a poster: put its JPEG in assets/posters/, edit POSTERS below, then run
    python3 tools/build_posters.py && python3 tools/build_present.py
"""
import base64, html, io, os, re, zipfile
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
os.chdir(ROOT)
DIR = 'assets/posters'

# One poster per distinct piece of content (colour and layout variants of the same content are left out).
POSTERS = [
    ('system-at-a-glance', 'Female reproductive system at a glance',
     'Poster with a labelled uterus diagram and ovary section, the six main organs, five functions, the four hormones, '
     'sperm and egg structure, a 28-day cycle wheel, the four steps of fertilization, a fun fact and self-care tips.'),
    ('system-and-fertilization', 'The system, its health and fertilization',
     'Illustrated poster of the main organs, the menstrual cycle, common conditions such as PCOS, endometriosis and fibroids, '
     'key hormones, the fertilization process, good-to-know health points and self-care tips.'),
    ('fertilization-diagram', 'Fertilization diagram',
     'Labelled fertilization diagram showing sperm structure, the parts of the egg cell, and four stages from sperm '
     'approaching the egg to the zygote forming.'),
    ('path-of-fertilization', 'The path of fertilization',
     'Diagram of the route sperm take from the vagina through the cervix and uterus into the fallopian tube and ampulla, '
     'then fertilization, cleavage and implantation as a blastocyst.'),
]

def save(im, name, fmt, **kw):
    im.save(f'{DIR}/{name}', fmt, **kw)
    return os.path.getsize(f'{DIR}/{name}')

def resized(im, w):
    return im if im.width <= w else im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)

items, total = [], {}
for slug, title, alt in POSTERS:
    im = Image.open(f'{DIR}/{slug}.jpg').convert('RGB')
    w, h = im.size
    sizes = {}
    t320, t560 = resized(im, 320), resized(im, 560)
    sizes['thumb-320.avif'] = save(t320, f'{slug}-thumb-320.avif', 'AVIF', quality=45)
    sizes['thumb-560.avif'] = save(t560, f'{slug}-thumb-560.avif', 'AVIF', quality=45)
    sizes['thumb-560.webp'] = save(t560, f'{slug}-thumb-560.webp', 'WEBP', quality=72, method=6)
    if w > 720:  # a phone-sized version, only when the original is bigger than that
        sizes['720.avif'] = save(resized(im, 720), f'{slug}-720.avif', 'AVIF', quality=62)
    sizes['full.avif'] = save(im, f'{slug}-full.avif', 'AVIF', quality=62)
    sizes['full.webp'] = save(im, f'{slug}-full.webp', 'WEBP', quality=80, method=6)
    sizes['original.jpg'] = os.path.getsize(f'{DIR}/{slug}.jpg')
    for k, v in sizes.items():
        total[k] = total.get(k, 0) + v
    # ~300-byte blurred preview, shown behind the image until it loads
    buf = io.BytesIO(); im.resize((12, round(h * 12 / w)), Image.LANCZOS).save(buf, 'WEBP', quality=40)
    lqip = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    p = f'assets/posters/{slug}'
    avif_set = (f'{p}-720.avif 720w, ' if w > 720 else '') + f'{p}-full.avif {w}w'
    items.append(f'''      <li><a href="{p}.jpg" data-title="{html.escape(title)}" data-w="{w}" data-h="{h}"
             data-avif="{avif_set}" data-webp="{p}-full.webp" data-thumb="{p}-thumb-560.webp">
        <picture>
          <source type="image/avif" srcset="{p}-thumb-320.avif 320w, {p}-thumb-560.avif 560w" sizes="(min-width: 72rem) 17rem, (min-width: 40rem) 24vw, 46vw">
          <img src="{p}-thumb-560.webp" width="560" height="{round(h * 560 / w)}" loading="lazy" decoding="async"
               style="background-image:url({lqip})" alt="{html.escape(alt)}">
        </picture>
        <span>{html.escape(title)}</span></a></li>''')

# Gallery markup in index.html, between the markers
idx = open('index.html').read()
block = '<!-- GALLERY:START (generated by tools/build_posters.py) -->\n' + '\n'.join(items) + '\n      <!-- GALLERY:END -->'
idx, n = re.subn(r'<!-- GALLERY:START.*?<!-- GALLERY:END -->', lambda m: block, idx, flags=re.S)
assert n == 1, 'gallery markers not found in index.html'

# Download-all ZIP of the untouched originals
zpath = f'{DIR}/from-two-cells-to-life-posters.zip'
with zipfile.ZipFile(zpath, 'w', zipfile.ZIP_STORED) as z:
    for k, (slug, _, _) in enumerate(POSTERS, 1):
        z.write(f'{DIR}/{slug}.jpg', f'{k:02d}-{slug}.jpg')
mb = os.path.getsize(zpath) / 1e6
idx = re.sub(r'Download all posters \(ZIP, [\d.]+ MB\)', f'Download all posters (ZIP, {mb:.1f} MB)', idx)
idx = re.sub(r'<p>The \w+ posters made for our exhibit\.', f'<p>The {len(POSTERS)} posters made for our exhibit.', idx)
open('index.html', 'w').write(idx)

print(f'{len(POSTERS)} posters')
for k, v in total.items():
    print(f'  {k:16s} {v / 1024:7.0f} KB total')
